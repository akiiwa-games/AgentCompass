// Exercise the actual installed Pi loader and request hook without a model call.
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {pathToFileURL} from 'node:url';
import assert from 'node:assert/strict';
const loader=process.argv[2]??path.join(os.homedir(),'AppData/Roaming/npm/node_modules/@earendil-works/pi-coding-agent/dist/core/extensions/loader.js');
const {loadExtensions}=await import(pathToFileURL(loader));
const extension=path.join(os.homedir(),'.pi/agent/extensions/fast-mode.ts');
const result=await loadExtensions([extension],process.cwd());
assert.equal(result.errors.length,0,JSON.stringify(result.errors));
assert.equal(result.extensions.length,1);
const handlers=result.extensions[0].handlers.get('before_provider_request');
assert.equal(handlers?.length,1);
const state=JSON.parse(fs.readFileSync(path.join(os.homedir(),'.pi/agent/fast-mode.json'),'utf8'));
const ctx={model:{provider:'openai-codex',api:'openai-codex-responses'},hasUI:false};
const body={model:'fixture-no-network',input:[],custom:'preserved'};
const value=await handlers[0]({type:'before_provider_request',payload:body},ctx);
assert.equal(value.service_tier,state.enabled?'priority':'default');
assert.equal(value.custom,'preserved');
assert.equal(body.service_tier,undefined);
assert.equal(await handlers[0]({type:'before_provider_request',payload:body},{...ctx,model:{provider:'anthropic',api:'anthropic-messages'}}),undefined);
console.log(JSON.stringify({extension,loader,loadErrors:0,requestTier:value.service_tier,otherProviderUntouched:true,networkRequests:0}));
